def build_pdf() -> None:
    s = styles()
    doc = SimpleDocTemplate(
        str(OUT_PDF),
        pagesize=A4,
        leftMargin=20 * mm,
        rightMargin=20 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        title="Оборудование для трансляций — конспект",
        author="ТЕХ ГУАП · направление ПТС",
    )
    story = []

    story.append(Paragraph("ОБОРУДОВАНИЕ ДЛЯ ТРАНСЛЯЦИЙ", s["title"]))
    story.append(Paragraph("Конспект для слушателей · направление ПТС", s["subtitle"]))

    story.append(Paragraph("Тезисы на занятие:", s["h_theses"]))
    for t in THESES:
        story.append(plain_dash(t, s))
    story.append(hr())

    # --- 1 ---
    story.append(Paragraph("Часть 1. Логика занятия", s["part"]))
    story.append(
        Paragraph(
            "Цель занятия — не выучить каталог моделей наизусть, а научиться выбирать железо "
            "через цепочку мышления: "
            f"{b('какая задача → какое соединение → какое оборудование')}. "
            "Спецификации (разрешения, частоты, марки) подтягиваются на практике; "
            "здесь важны роли узлов в тракте и типовые ошибки.",
            s["body"],
        )
    )
    story.append(hr())

    # --- 2 ---
    story.append(Paragraph("Часть 2. Карта мира эфира", s["part"]))
    story.append(
        Paragraph(
            f"{u(b('Трансляция'))} – путь аудиовидеосигнала от места события к зрителю "
            f"(эфир, запись, удалённый зал, платформа).",
            s["body"],
        )
    )
    story.append(Paragraph(f"{u('Четыре блока пайплайна:')}", s["subhead"]))
    for term, desc in [
        ("Источник", "камеры, ПК/ноутбуки, внешний сигнал (уже готовая программа)."),
        ("Путь", "кабели, сеть, преобразователи сигнала."),
        ("Обработка", "микшер, скейлер, матрица, рабочая станция."),
        ("Вывод", "стрим, запись, экраны зала, раздача на площадке."),
    ]:
        story.append(dash(term, desc, s))
    story.append(
        Paragraph(
            f"{b('Диагностика:')} если эфир «упал», идите слева направо — от источника к выводу — "
            f"и ищите, на каком звене сигнал умер.",
            s["body"],
        )
    )
    story.append(hr())

    # --- 3 ---
    story.append(Paragraph("Часть 3. Источники сигнала", s["part"]))

    story.append(Paragraph(f"{u(b('3.1. Камеры'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Источник сигнала'))} – устройство, которое впервые формирует видео "
            f"и отдаёт его наружу вместе с параметрами формата.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            "Типичные выходы камеры: <b>SDI (BNC)</b>, <b>HDMI</b>, иногда <b>NDI</b> (видео по IP). "
            "Параметры формата: разрешение, частота кадров, progressive / interlace, иногда цветовое пространство.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{b('В первую очередь проверяем здесь:')} формат, выход и другие параметры источника. "
            f"Без стабильного сигнала с камеры искать ошибку дальше по тракту бессмысленно.",
            s["note"],
        )
    )

    story.append(Paragraph(f"{u(b('3.2. ПК и ноутбуки'))}", s["subhead"]))
    story.append(
        Paragraph(
            "Компьютер в эфире — прежде всего источник <b>компьютерной графики</b>: "
            "презентации, браузер, окна приложений, титры, графика микшера.",
            s["body"],
        )
    )
    for term, desc in [
        ("Выход", "HDMI / DisplayPort / USB-C; при необходимости — адаптер форм-фактора."),
        ("Сетевые протоколы", "NDI, SRT, RTMP и другие пути передачи «по IP»."),
        (
            "EDID",
            "данные о возможностях дисплея/приёмника. Без корректного EDID ПК может отдать "
            "неверный режим (разрешение, частота), и «картинки нет» при живом кабеле.",
        ),
    ]:
        story.append(dash(term, desc, s))
    story.append(
        Paragraph(
            f"{b('Важно:')} HDMI на ноутбуке/ПК — <b>всегда</b> только выход, не вход. "
            f"Чтобы принять видео в компьютер, нужна карта захвата (USB или PCIe).",
            s["note"],
        )
    )

    story.append(Paragraph(f"{u(b('3.3. Внешний сигнал'))}", s["subhead"]))
    story.append(
        Paragraph(
            "Внешний сигнал — уже готовая программа: PGM с другого микшера, плеер/медиасервер, "
            "ВКС/телемост. У него тоже есть интерфейс и формат — их нужно согласовать так же, "
            "как у камеры.",
            s["body"],
        )
    )
    story.append(hr())

    # --- 4 glossary ---
    story.append(Paragraph("Часть 4. Базовые термины", s["part"]))
    story.append(
        Paragraph(
            f"{u(b('Интерфейс'))} – способ взаимодействия и обмена данными между устройствами "
            f"(или человеком и устройством): физический разъём + правила обмена. "
            f"Примеры: HDMI, SDI, USB, Ethernet.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{u(b('Протокол'))} – набор правил, по которым устройства «понимают» друг друга "
            f"при обмене данными. Примеры: RTMP, SRT, NDI, TCP/IP, HTTP.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{u(b('Формат'))} – полный набор параметров сигнала/файла: разрешение, частота кадров, "
            f"развёртка (progressive/interlace), кодирование, иногда цветовое пространство и звук.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{u(b('Тракт сигнала'))} – упорядоченная последовательность звеньев, по которой сигнал "
            f"проходит от источника к конечному приёмнику (кабель, сеть, конвертер, микшер, вывод).",
            s["body"],
        )
    )
    story.append(hr())

    # --- 5 cables ---
    story.append(Paragraph("Часть 5. Кабели и интерфейсы", s["part"]))
    story.append(
        Paragraph(
            "Кабель в эфире — не «просто провод», а стандарт: "
            f"{b('разъём + электрический/цифровой протокол + ограничения по длине')}.",
            s["body"],
        )
    )
    for term, desc in [
        (
            "HDMI",
            "бытовой/компьютерный видео+звук. Короткие линии, чувствителен к качеству кабеля и EDID.",
        ),
        (
            "SDI (BNC)",
            "профессиональное видео. Разъём BNC. Level A / Level B — разные упаковки 3G-SDI. "
            "Длиннее и стабильнее HDMI на площадке.",
        ),
        ("XLR", "балансный звуковой интерфейс для микрофонов и линейных сигналов."),
        (
            "Ethernet (RJ45)",
            "сеть, управление, стрим и другие средства передачи по IP (в т.ч. NDI, управление PTZ).",
        ),
    ]:
        story.append(dash(term, desc, s))
    story.append(hr())

    # --- 6 converters family ---
    story.append(Paragraph("Часть 6. Преобразователи сигнала", s["part"]))
    story.append(
        Paragraph(
            "«Преобразование» на занятии — общее обозначение устройств на пути сигнала: "
            "не только смена типа интерфейса, но и разветвление, согласование разъёмов, "
            "соединение линий. Четыре семейства:",
            s["body"],
        )
    )

    story.append(Paragraph(f"{u(b('6.1. Конверторы'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Конвертер'))} меняет <b>стандарт</b> сигнала (типично HDMI ↔ SDI). "
            f"Обычно требует питание и содержит чип обработки. Может выполнять up/down/cross conversion "
            f"и embed/de-embed звука (вложить звук в видео или вынуть).",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{b('Правило:')} разные разъёмы <b>и</b> разные протоколы → нужен конвертер, а не «переходник».",
            s["note"],
        )
    )

    story.append(Paragraph(f"{u(b('6.2. Адаптеры'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Адаптер'))} меняет только форм-фактор разъёма (пример: HDMI ↔ DVI). "
            f"Он не превращает HDMI в SDI и не устраняет несовместимость формата кадра.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{b('Ошибка новичка:')} ожидать от адаптера работу конвертера стандартов.",
            s["note"],
        )
    )

    story.append(Paragraph(f"{u(b('6.3. Сплиттеры'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Сплиттер (distribution amplifier, DA)'))} – один вход, несколько одинаковых копий "
            f"на выходы (микшер + рекордер + превью одновременно).",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            "Активный сплиттер (с питанием и усилением/восстановлением сигнала) предпочтительнее "
            "пассивного разветвителя, который делит энергию сигнала и повышает риск срыва приёма.",
            s["body"],
        )
    )

    story.append(Paragraph(f"{u(b('6.4. Соединители (бочонки)'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Бочонок (barrel / coupler)'))} – механическое стыкование двух однотипных кабелей "
            f"(например BNC–BNC), чтобы удлинить линию или сменить «пол» разъёма. "
            f"Каждое лишнее соединение — дополнительная точка отказа.",
            s["body"],
        )
    )

    story.append(Paragraph(f"{u('Типовая связка')}", s["subhead"]))
    story.append(
        Paragraph(
            "<b>Камера HDMI → конвертер HDMI→SDI → SDI-сплиттер → микшер / запись / превью.</b> "
            "Где ошибаются: ставят адаптер вместо конвертера; забывают питание конвертера; "
            "путают параметры сигнала (формат).",
            s["body"],
        )
    )
    story.append(hr())

    # --- 7 processing ---
    story.append(Paragraph("Часть 7. Обработка", s["part"]))
    story.append(
        Paragraph(
            "На этапе обработки из входных сигналов формируют программу: переключают, "
            "масштабируют и маршрутизируют.",
            s["body"],
        )
    )

    story.append(Paragraph(f"{u(b('7.1. Видеомикшер (switcher)'))}", s["subhead"]))
    story.append(
        Paragraph(
            "Устройство или программа, которое в реальном времени выбирает, что идёт в программу, "
            "держит превью, выполняет переходы, PinP и ключи.",
            s["body"],
        )
    )
    for term, desc in [
        ("PGM (Program)", "то, что сейчас в эфире / в программе."),
        ("PVW (Preview)", "следующий кандидат на переход в программу."),
        ("AUX", "дополнительный выход с отдельным назначением (монитор, запись, зал)."),
    ]:
        story.append(dash(term, desc, s))
    story.append(
        Paragraph(
            "Пример с занятия: <b>Roland V-60HD</b> — гибридный микшер (4× SDI + 2× HDMI входа; "
            "выходы PGM / AUX / Multi-View; встроенный звук).",
            s["body"],
        )
    )

    story.append(Paragraph(f"{u(b('7.2. Скейлер'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Скейлер'))} приводит входной кадр к требуемому формату отображения: "
            f"разрешению, соотношению сторон и ориентации — без искажения пропорций.",
            s["body"],
        )
    )
    story.append(
        Paragraph(
            f"{b('Кейс:')} вход Full HD 1920×1080, экран 768×1280 (вертикальный). "
            f"Решение — масштабирование и подгонка (fit / crop) в устройстве раздачи. "
            f"Ошибка — принудительный stretch (растяжение), ломающий пропорции. "
            f"Пример железа: Roland VC-100UHD.",
            s["body"],
        )
    )

    story.append(Paragraph(f"{u(b('7.3. Матрица / Videohub'))}", s["subhead"]))
    story.append(
        Paragraph(
            f"{u(b('Матрица (router / Videohub)'))} – коммутатор M входов на N выходов "
            f"с независимым назначением маршрутов.",
            s["body"],
        )
    )
    for term, desc in [
        ("Сплиттер", "один вход → одинаковые копии на все выходы."),
        ("Матрица", "входы и выходы назначаются независимо (любой → любой)."),
        ("Пресеты", "снижают необходимость перекоммутации кабелей в эфире."),
    ]:
        story.append(dash(term, desc, s))
    story.append(
        Paragraph(
            "На корпусе: спереди — управление (кнопки, экран, энкодер); сзади — разъёмы SDI "
            "(пример: Blackmagic Smart Videohub 20×20).",
            s["body"],
        )
    )
    story.append(hr())

    # --- 8 station ---
    story.append(Paragraph("Часть 8. Станция: захват, вывод, GPU", s["part"]))

    story.append(Paragraph(f"{u(b('8.1. Карты захвата (capture)'))}", s["subhead"]))
    story.append(
        Paragraph(
            "Карта захвата принимает SDI/HDMI и передаёт кадры в компьютер / микшерное ПО.",
            s["body"],
        )
    )
    for term, desc in [
        (
            "USB (внешний бокс)",
            "подключается к порту USB. Удобен для ноутбука. Полоса делится с другими устройствами; "
            "стабильность зависит от чипа и драйвера.",
        ),
        (
            "PCIe (внутренняя плата)",
            "ставится в слот системной платы (x4/x8/x16). Выше запас по полосе, удобнее многоканальные входы.",
        ),
    ]:
        story.append(dash(term, desc, s))
    story.append(
        Paragraph(
            f"{b('Как отличить:')} USB — отдельный корпус к порту компьютера; "
            f"PCIe — плата с контактной «гребёнкой» внутрь корпуса ПК.",
            s["note"],
        )
    )

    story.append(Paragraph(f"{u(b('8.2. Вывод программы'))}", s["subhead"]))
    story.append(
        Paragraph(
            "После обработки программу возвращают в тракт устройствами вывода — "
            "это <b>не</b> мониторный выход игровой видеокарты.",
            s["body"],
        )
    )
    for term, desc in [
        (
            "Внешний бокс вывода",
            "пример: Blackmagic UltraStudio Monitor 3G — принимает программу со станции "
            "и отдаёт SDI/HDMI в эфирный тракт или на контрольный монитор.",
        ),
        (
            "PCIe SDI + HDMI",
            "плата в слот ПК; типовая роль — захват и/или playback в профессиональный тракт.",
        ),
    ]:
        story.append(dash(term, desc, s))
    story.append(
        Paragraph(
            f"{b('Связка:')} захват → обработка на станции → вывод. "
            f"HDMI ноутбука/ПК всегда только выход и не заменяет вход захвата.",
            s["note"],
        )
    )

    story.append(Paragraph(f"{u(b('8.3. Видеокарты (GPU)'))}", s["subhead"]))
    story.append(
        Paragraph(
            "На эфирной станции GPU — ускоритель композиции, кодирования стрима и вывода "
            "на мониторы оператора. Её не следует путать с картой захвата или платой "
            "профессионального вывода в тракт.",
            s["body"],
        )
    )
