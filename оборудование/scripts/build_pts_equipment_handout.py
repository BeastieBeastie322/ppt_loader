def u(text: str) -> str:
    return f"<u>{text}</u>"


def b(text: str) -> str:
    return f"<b>{text}</b>"


def dash(term: str, desc: str, s) -> Paragraph:
    return Paragraph(f"— {b(term)} – {desc}", s["bullet"])


def plain_dash(text: str, s) -> Paragraph:
    return Paragraph(f"— {text}", s["bullet"])


def hr():
    return HRFlowable(
        width="100%",
        thickness=0.6,
        color=(0.55, 0.55, 0.55),
        spaceBefore=8,
        spaceAfter=8,
    )


